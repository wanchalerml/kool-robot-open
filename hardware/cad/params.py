# ---------------------------------------------------------------- เครื่อง/สไลซ์
PRINTER = "Bambu Lab X2D"
NOZZLE = 0.4            # หัวฉีด
LAYER = 0.2             # ความสูงชั้นที่ใช้ออกแบบ
MATERIAL = "PLA Basic"  # วัสดุที่ใช้คาลิเบรต (BHL แนะนำ Bambu PLA Basic)

# ค่าสไลซ์ที่ใช้ตอนคาลิเบรต — ถ้าเปลี่ยนค่าเหล่านี้ใน Bambu Studio ต้องพิมพ์ทดสอบใหม่
SLICER = dict(process="0.20mm Standard @BBL X2D", xy_hole_comp=0.0, xy_contour_comp=0.0,
              elephant_foot_comp=0.15, wall_loops=2, infill=0.15)

# ---------------------------------------------------------------- ผนัง/พื้น
MIN_WALL = 1.2          # ผนังขั้นต่ำ = 3 เส้น × 0.4 (ชิ้นรับแรงใช้ ≥ 2.0)
STRUCT_WALL = 2.0       # ผนังชิ้นรับแรง (5 เส้น)
MIN_FLOOR = 0.8         # พื้น/เพดานขั้นต่ำ = 4 ชั้น × 0.2
MIN_FEATURE = 0.8       # ครีบ/ตัวอักษรนูนเล็กสุดที่พิมพ์ได้ชัด (2 เส้น)

# ---------------------------------------------------------------- ระยะเผื่อเพลา/รู (diametral)
# ผลทดสอบรอบ 1 (หมุด ⌀5 ในรูแนวตั้ง): .1 แน่นถอดมือได้ · .2 ลื่นหมุนได้ · .3–.5 หลวมโยก
# ทดสอบละเอียดทีละ 0.1 → ค่าจริงอาจอยู่ระหว่างช่อง · ใช้กับรูแนวตั้ง ⌀ ~3–8 มม. (รูใหญ่ควรทดสอบซ้ำ)
FIT_PRESS = 0.05        # อัดแน่น (bearing/หมุดที่ไม่ถอด) — ยังไม่ได้ทดสอบ (ประมาณจาก .1 = แน่นถอดได้)
FIT_SNUG = 0.10         # สวมแน่น ถอดได้ด้วยมือ  (ทดสอบแล้ว ✓)
FIT_SLIDE = 0.20        # สวมลื่น หมุนได้ (เพลาเฟือง)  (ทดสอบแล้ว ✓)
FIT_LOOSE = 0.30        # หลวม หมุนอิสระ (มีโยก)  (ทดสอบแล้ว ✓)

# รูแนวตั้ง (แกน Z) พิมพ์ออกมาเล็กกว่าแบบ ~0.1–0.2 · รูแนวนอนเพิ่มอีกเพราะเพดานย้อย
HORIZONTAL_HOLE_EXTRA = 0.10

# ---------------------------------------------------------------- น็อต/สกรู
# ขนาดมาตรฐาน ISO 4032 (น็อตหกเหลี่ยม) + รูสกรูผ่าน (ISO 273 medium + เผื่อ FDM)
SCREWS = {
    #       รูผ่าน   ข้ามแบน(น็อต)  หนาน็อต  หัว SHCS ⌀  หัวสูง
    "M2":  dict(clear=2.4, nut_af=4.0, nut_h=1.6, head_d=3.8, head_h=2.0),
    "M2.5": dict(clear=2.9, nut_af=5.0, nut_h=2.0, head_d=4.5, head_h=2.5),
    "M3":  dict(clear=3.4, nut_af=5.5, nut_h=2.4, head_d=5.5, head_h=3.0),
    "M4":  dict(clear=4.5, nut_af=7.0, nut_h=3.2, head_d=7.0, head_h=4.0),
    "M5":  dict(clear=5.5, nut_af=8.0, nut_h=4.7, head_d=8.5, head_h=5.0),
}
NUT_AF_OFFSET = 0.25     # เผื่อช่องน็อต (บวกกับ "ข้ามแบน") ให้กดน็อตลงได้แน่นพอดี
NUT_DEPTH_EXTRA = 0.20   # เผื่อความลึกช่องน็อต
SCREW_TAP_DIA = {"M2": 1.7, "M2.5": 2.1, "M3": 2.6, "M4": 3.5}  # รูต๊าปเกลียวลงพลาสติกตรง

# เม็ดเกลียวฝังร้อน (heat-set insert) แบบสั้นทั่วไป — ค่าตั้งต้น ปรับตามยี่ห้อที่ซื้อ
HEAT_SET = {
    "M3": dict(hole=4.0, depth=5.0),
    "M4": dict(hole=5.6, depth=6.0),
}

# ---------------------------------------------------------------- ขอบ/ฐาน
ELEPHANT_FOOT_CHAMFER = 0.4   # ลบมุมขอบล่างกันขอบบาน (ชั้นแรกโดนกด)
TOP_CHAMFER = 0.3             # ลบมุมปากรูให้สวมง่าย

# ---------------------------------------------------------------- ฟังก์ชันช่วย


def hole_d(nominal: float, fit: str = "slide", horizontal: bool = False) -> float:
    """เส้นผ่านศูนย์กลางรูที่ต้องวาด สำหรับเพลาขนาด nominal."""
    extra = {"press": FIT_PRESS, "snug": FIT_SNUG, "slide": FIT_SLIDE, "loose": FIT_LOOSE}[fit]
    return nominal + extra + (HORIZONTAL_HOLE_EXTRA if horizontal else 0.0)


def screw_clear(size: str) -> float:
    """รูสกรูผ่าน."""
    return SCREWS[size]["clear"]


def nut_af(size: str) -> float:
    """ระยะข้ามแบนของช่องน็อตที่ต้องวาด."""
    return SCREWS[size]["nut_af"] + NUT_AF_OFFSET


def nut_depth(size: str) -> float:
    """ความลึกช่องน็อต."""
    return SCREWS[size]["nut_h"] + NUT_DEPTH_EXTRA


