"""ชิ้นทดสอบคานเท้า PAHT-CF + วิธีทดสอบแขวน 70 กก. 24 ชม. (KOOL 27 พ.ย. 2569 · PAHT-CF 00:43)

ใช้ "คานนอก" จริงจาก foot_v1.py (รันก่อน) → วางนอนบนฐาน (หนา 15 = แกน z) → STL พร้อมสไลซ์
การทดสอบ = ดัด 3 จุด (เหมือนใช้งานจริงกลับหัว): รองที่รูเพลาล้อ 2 ข้าง (ห่าง 200) · แขวนน้ำหนักที่รูกลาง (เพลาข้อเท้า)
⚠️ ยังไม่พิมพ์ · พิมพ์ต้องรอ อนุญาต
"""
import math, os
import numpy as np
import trimesh

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "out")
SPAN = 200.0              # ระยะรูเพลาล้อ (HALF_WB × 2)
T, H = 15.0, 30.0         # หน้าตัดแขนคาน (หนา × ลึก) ตาม foot_v1.strength_report
E_DRY, E_WET = 4120.0, 3640.0   # PAHT-CF ดัด XY (datasheet Bambu)
LOAD_KG = 70.0
STAND_PLATE = 11.4 / 2    # กก./แผ่น ตอนยืนปกติ (ข้อเท้ารับ 11.4 · 2 แผ่น)
DESIGN_PLATE = 68.0 / 2   # กก./แผ่น กรณีออกแบบ (ขาเดียว × กระแทก 3)


def main():
    m = trimesh.load(os.path.join(OUT, "show_v1_foot1_คานนอก.stl"))
    m.apply_transform(trimesh.transformations.rotation_matrix(math.pi / 2, [1, 0, 0]))   # หนา y → z
    m.apply_translation(-m.bounds[0] + [0, 0, 0])
    ex = m.extents
    p = os.path.join(OUT, "show_v1_foot1_TEST_คานทดสอบแขวน_PAHT-CF.stl")
    m.export(p)
    I = T * H ** 3 / 12
    P = LOAD_KG * 9.81
    d = [P * SPAN ** 3 / (48 * E * I) for E in (E_DRY, E_WET)]
    sig = P * SPAN / 4 / (T * H ** 2 / 6)
    g = m.volume * 1.20e-3   # PAHT-CF ~1.20 g/cm³ (ผนัง 6 + infill 60% ≈ ใกล้ตัน)
    rep = [
        "ชิ้นทดสอบคานเท้า PAHT-CF (ฉบับร่าง · ยังไม่พิมพ์ · รอ อนุญาต)",
        f"ไฟล์: {os.path.basename(p)} · กล่อง {ex[0]:.0f}×{ex[1]:.0f}×{ex[2]:.0f} มม. (นอนราบ) · ~{g:.0f} ก. · พอดีฐาน X2D",
        "พิมพ์ (ตั้งเหมือนชิ้นจริง): PAHT-CF อบแห้ง 80 °C 12 ชม. ก่อน · หัวฉีดเหล็กแข็ง 0.4/0.6 · ผนัง 6 · บน/ล่าง 6 ชั้น · infill 60% gyroid · ชั้น 0.2 · ห้องปิด",
        "  หลังพิมพ์: อบคลายเครียด 80–100 °C 8 ชม. (datasheet แนะนำ 80–130 °C) แล้วเก็บในกล่องกันชื้น",
        "อุปกรณ์: แท่งเหล็ก/น็อต ⌀12 ×2 สอดรูเพลาล้อ วางบนโต๊ะ/ขาตั้ง 2 ข้าง (ห่าง 200) · ท่อ/แท่ง ⌀25–27 สอดรูกลาง ⌀28 + สายรัดแขวน",
        f"  น้ำหนัก ~{LOAD_KG:.0f} กก. (ขวดน้ำ 6 ลิตร ×12 / ถุงทราย) ค่อย ๆ เพิ่ม · ไม้บรรทัดเหล็ก/ไดอัลเกจวัดการแอ่นที่รูกลาง",
        f"เทียบโหลด: ทดสอบ {LOAD_KG:.0f} กก./แผ่น = {LOAD_KG/DESIGN_PLATE:.1f}× กรณีออกแบบ ({DESIGN_PLATE:.0f} กก./แผ่น) · {LOAD_KG/STAND_PLATE:.0f}× ยืนปกติ ({STAND_PLATE:.1f} กก./แผ่น)",
        f"คาดการณ์: แอ่นทันที ~{d[0]:.1f}–{d[1]:.1f} มม. · แรงดัดที่กลาง ~{sig:.0f} MPa (datasheet ดัด 115–125 MPa → เผื่อ ~{120/sig:.1f}×)",
        "ขั้นตอน: ① วัดศูนย์ ② ใส่น้ำหนักทีละ 10 กก. จด δ ③ ครบ 70 กก. จด δ ที่ 1 นาที / 1 ชม. / 24 ชม. ④ ถอดน้ำหนัก จด δ ค้างที่ 1 ชม.",
        f"ผ่านเมื่อ: ไม่ร้าว/ไม่ขาวที่ผิว/ชั้นไม่แยก · δ 24 ชม. ≤ 2× δ 1 นาที และ ≤ 2.5 มม. · ถอดแล้วคืนตัว ≥ 80% (ค้าง ≤ 0.5 มม.)",
        "ไม่ผ่าน → ① เพิ่มหนาเป็น 18 / ผนัง 8 แล้วทดสอบใหม่ หรือ ② ROCKER=al (แผ่น Al 6061 หนา 6 ตัดเลเซอร์ · DXF พร้อม)",
        "ปลอดภัย: แขวนเตี้ย (น้ำหนักห่างพื้น ≤ 5 ซม.) · อย่ายืน/วางเท้าใต้น้ำหนัก · ใส่แว่นกันเศษ",
    ]
    txt = "\n".join(rep)
    open(os.path.join(OUT, "show_v1_foot1_TEST_report.txt"), "w").write(txt + "\n")
    print(txt)


if __name__ == "__main__":
    main()
