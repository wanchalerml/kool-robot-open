"""หุ่นโชว์ v1 (ไม่มีมอเตอร์ข้อต่อ · ล้อที่เท้า) — มวล/จุดศูนย์ถ่วง/มุมล้ม · KOOL 24 พ.ย. 2569 #robot-show-v1
ความสูงตามสัดส่วน K-Bot 1.40 ม. · ตัวเลขมวลเป็นค่าประมาณจากวัสดุ (ชั่งจริงแล้วแก้ในตาราง P)"""
import numpy as np
P = [  # ชิ้น, กก., ความสูงจุดศูนย์ถ่วง (ม.)
    ("หัว+หน้ากาก+จอ 7\"+ตาไฟ", 1.2, 1.30),
    ("ลำตัว: เปลือก+โครง+Pi+ลำโพง+ไมค์", 4.0, 1.00),
    ("แขน 2 ข้าง (ท่อ+ข้อหนืด+เปลือก)", 3.2, 0.95),
    ("สะโพก (แผ่นอะลูมิเนียม+เปลือก)", 1.5, 0.72),
    ("ต้นขา 2 ข้าง", 2.8, 0.55),
    ("หน้าแข้ง 2 ข้าง", 2.0, 0.25),
    ("แบต LiFePO4 24V 10Ah ×2 (ในเท้า)", 4.8, 0.07),
    ("เท้า ×2: ล้อ hub 5\" มีเบรก + ล้อหมุนตาม + แผ่นเท้า", 5.5, 0.06),
]
M = sum(p[1] for p in P); Z = sum(p[1] * p[2] for p in P) / M
print(f"มวลรวม ~{M:.1f} กก. · จุดศูนย์ถ่วง ~{Z:.2f} ม.")
for half in (0.135, 0.15, 0.20, 0.22):  # ±22 ซม. = ค่าที่เลือก (ตามภาพแนวคิดรอบ 3)
    print(f"  ล้อห่างกลางตัว ±{half*100:.1f} ซม. (กว้างนอก-นอก ~{2*half*100+3:.0f}) → ล้มข้างที่ {np.degrees(np.arctan(half / Z)):.1f}°")
for L in (0.23, 0.27, 0.30):
    print(f"  ระยะล้อหน้า-หลัง {L*100:.0f} ซม. → ล้มหน้า/หลังที่ {np.degrees(np.arctan(L / 2 / Z)):.1f}° (CoM กลางเท้า)")
print(f"  ต้องการ ≥15°: ข้าง ±{Z*np.tan(np.radians(15))*100:.1f} ซม. · หน้า-หลัง ≥ {2*Z*np.tan(np.radians(15))*100:.0f} ซม.")
print(f"  เบรกจากเดินช้า 0.5 ม./วิ ใน 0.5 วิ (1 ม./วิ²) = เอียงเทียบเท่า {np.degrees(np.arctan(1/9.81)):.1f}°")
